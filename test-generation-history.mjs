import {strict as assert} from 'node:assert';
import {generationHistoryPage,articleEditor} from './scripts/admin-view.mjs';
import {recordGeneration,generationHistory,generationDetail,linkGeneration} from './scripts/admin-generation-history.mjs';
import {DatabaseSync} from 'node:sqlite';
const articles=[{slug:'draft-one',draft:JSON.stringify({title:'임시 원고'}),updated:'2026-11-16T08:00:00.000Z-x',published:null},{slug:'public-one',draft:JSON.stringify({title:'공개 원고'}),updated:'2026-11-16T08:00:00.000Z-x',published:'{}'}];
const id='00000000-0000-4000-8000-000000000001';
const page=generationHistoryPage([{id,title:'생성 <원고>',keyword:'티벗',created:'2026-11-16T08:00:00.000Z',slug:'draft-one'}],articles);
assert(page.includes('/admin/article-preview?slug=draft-one'));
assert(page.includes('/review/notice/public-one/'));
assert(page.includes('생성 &lt;원고&gt;'));
assert(page.includes('/admin/history-link'));
assert(page.includes('티벗'));
assert(page.includes('/assets/tvut-history.js'));
assert(articleEditor().includes('id="generation-id"'));
assert(articleEditor().includes('id="ai-keyword"'));
const sqlite=new DatabaseSync(':memory:');
const db={prepare(sql){let args=[];return {bind(...values){args=values;return this},async run(){return sqlite.prepare(sql).run(...args)},async first(){return sqlite.prepare(sql).get(...args)},async all(){return {results:sqlite.prepare(sql).all(...args)}}}},async batch(statements){return Promise.all(statements.map(x=>x.run()))}};
const generated=await recordGeneration(db,'제목','설명','본문','회원가입');
assert.equal((await generationDetail(db,generated)).body,'본문');
await linkGeneration(db,generated,'draft-one');
const rows=await generationHistory(db);
assert.equal(rows[0].slug,'draft-one');
assert.equal(rows[0].keyword,'회원가입');
await assert.rejects(()=>linkGeneration(db,generated,'../../invalid'));
sqlite.close();
console.log('generation history: passed');
